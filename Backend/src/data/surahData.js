/**
 * الحصول على اسم السورة من رقمها
 * @param {number} surahNumber 
 * @returns {string|null}
 */
function getSurahName(surahNumber) {
  return SURAH_ARABIC_NAMES[surahNumber] || null;
}

/**
 * الحصول على عدد آيات السورة
 * @param {number} surahNumber 
 * @returns {number|null}
 */
function getSurahAyahCount(surahNumber) {
  return SURAH_AYAH_COUNT[surahNumber] || null;
}

/**
 * التحقق من صحة رقم الآية
 * @param {number} surahNumber 
 * @param {number} ayahNumber 
 * @returns {{ valid: boolean, maxAyah?: number, surahName?: string, error?: string }}
 */
function validateAyahNumber(surahNumber, ayahNumber) {
  const maxAyah = SURAH_AYAH_COUNT[surahNumber];
  const surahName = SURAH_ARABIC_NAMES[surahNumber];
  
  if (!maxAyah) {
    return { valid: false, error: 'invalid_surah' };
  }
  
  if (ayahNumber < 1 || ayahNumber > maxAyah) {
    return { 
      valid: false, 
      error: 'invalid_ayah', 
      maxAyah, 
      surahName 
    };
  }
  
  return { valid: true, maxAyah, surahName };
}

/**
 * الحصول على معلومات السورة الكاملة
 * @param {number} surahNumber 
 * @returns {{ number: number, name: string, ayahCount: number, aliases: string[] }|null}
 */
function getSurahInfo(surahNumber) {
  const surah = SURAH_CANONICAL.find(s => s.number === surahNumber);
  if (!surah) return null;
  
  return {
    number: surah.number,
    name: surah.names[0],
    ayahCount: SURAH_AYAH_COUNT[surah.number],
    aliases: surah.names.slice(1)
  };
}

