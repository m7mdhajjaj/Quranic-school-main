const path = require('path');
require('dotenv').config({ path: path.resolve(__dirname, '../../.env') });
const mongoose = require('mongoose');
const Student = require('../schema/Student');
const Attendance = require('../schema/Attendance');

// Connect to DB
const connectDB = async () => {
  try {
    await mongoose.connect(process.env.MONGODB_URI);
    console.log('✅ Connected to MongoDB');
  } catch (err) {
    console.error('❌ DB Connection Error:', err);
    process.exit(1);
  }
};

const runAutoAttendance = async () => {
  await connectDB();

  console.log("🤖 [Manual Trigger] بدء عملية الحضور التلقائي لليوم السابق...");
  try {
    // 1. تحديد تاريخ الأمس
    const yesterday = new Date();
    yesterday.setDate(yesterday.getDate() - 1);
    yesterday.setHours(0, 0, 0, 0);
    
    const endOfYesterday = new Date(yesterday);
    endOfYesterday.setHours(23, 59, 59, 999);

    console.log(`📅 معالجة تاريخ: ${yesterday.toLocaleDateString('en-GB')}`);

    // 2. جلب الطلاب
    const allStudents = await Student.find({}).select('_id firstName lastName');
    console.log(`👥 إجمالي الطلاب في النظام: ${allStudents.length}`);

    if (allStudents.length === 0) {
      console.log("⚠️ لا يوجد طلاب.");
      process.exit(0);
    }

    // 3. جلب سجلات الحضور الموجودة للأمس
    const existingRecords = await Attendance.find({
      date: {
        $gte: yesterday,
        $lte: endOfYesterday
      }
    }).select('studentId isPresent');

    console.log(`📝 سجلات الحضور الموجودة لهذا التاريخ: ${existingRecords.length}`);

    // 4. تحديد الطلاب الذين ليس لديهم سجل
    const recordedStudentIds = new Set(existingRecords.map(r => r.studentId.toString()));
    const studentsWithoutRecord = allStudents.filter(s => !recordedStudentIds.has(s._id.toString()));

    console.log(`🔍 طلاب ليس لديهم سجل (سيتم اعتبارهم حضور): ${studentsWithoutRecord.length}`);

    if (studentsWithoutRecord.length > 0) {
      console.log("--- عينة من الطلاب الذين سيتم تسجيلهم ---");
      studentsWithoutRecord.slice(0, 5).forEach(s => console.log(`- ${s.firstName} ${s.lastName}`));
      
      // 5. التنفيذ الفعلي (اختياري: يمكنك التعليق على هذا الجزء إذا كنت تريد فقط الفحص)
      const newRecords = studentsWithoutRecord.map(s => ({
        studentId: s._id,
        date: yesterday,
        isPresent: true,
        autoGenerated: true
      }));

      await Attendance.insertMany(newRecords, { ordered: false });
      console.log(`✅ تم حفظ ${newRecords.length} سجل حضور تلقائي بنجاح.`);
    } else {
      console.log("✅ جميع الطلاب لديهم سجلات بالفعل.");
    }

  } catch (error) {
    console.error("❌ خطأ:", error);
  } finally {
    await mongoose.disconnect();
    console.log("👋 تم الانتهاء.");
    process.exit(0);
  }
};

runAutoAttendance();
